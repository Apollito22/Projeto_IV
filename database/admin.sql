DO $$
DECLARE
    tabela TEXT;
    maior BIGINT;
BEGIN
    FOREACH tabela IN ARRAY ARRAY['conteudos', 'midias', 'auditoria'] LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = tabela AND column_name = 'id' AND is_identity = 'NO' AND column_default IS NULL) THEN
            EXECUTE format('ALTER TABLE %I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', tabela);
            EXECUTE format('SELECT COALESCE(MAX(id), 0) FROM %I', tabela) INTO maior;
            PERFORM setval(pg_get_serial_sequence(tabela, 'id'), GREATEST(maior, 1), maior >= 1);
        END IF;
    END LOOP;
END $$;
